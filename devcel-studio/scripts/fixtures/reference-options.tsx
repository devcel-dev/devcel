// Synthetic IPC/DOM regression scenarios; no native Tauri or layout assertions.
import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import React, { act } from 'react';
import { createRoot } from 'react-dom/client';
import { getReferenceOptions } from '../../src/app/pages/main_window/project_view/table_view/components/referenceOptions';
import { ReferenceCellRenderer, ReferenceCellEditor } from '../../src/app/pages/main_window/project_view/table_view/components/ReferenceCell';
export async function runReferenceOptionsChecks() {
    const originalError = console.error;
    const scope = { tableUuid: 'table', columnUuid: 'column', expectedProjectSession: 'session', targetTableUuid: 'target', displayColumnUuid: 'display' };
    const candidates = [{ uuid: 'a', display_value: 'Alpha' }, { uuid: 'b', display_value: '' }, { uuid: 'a', display_value: 'Duplicate' }];
    let calls: any[] = [];
    const deferred = () => { let resolve: any, reject: any; const promise = new Promise<any>((a, b) => { resolve = a; reject = b; }); return { promise, resolve, reject }; };
    (globalThis as any).__invoke = (command: any, args: any) => { calls.push({ command, args }); return Promise.resolve(candidates); };
    const sections: string[] = [];
    const done = (s: string) => { sections.push(s); console.log('PASS', s); };
    const snapshot: any = {};
    const first = getReferenceOptions(scope, snapshot, 0);
    const shared = Array.from({ length: 1000 }, () => getReferenceOptions({ ...scope }, snapshot, 0));
    assert(shared.every(p => p === first));
    const index = await first;
    assert.equal(calls.length, 1);
    assert.equal(index.byUuid.get('a')?.option.display_value, 'Alpha');
    assert.equal(index.byUuid.get('b')?.index, 1);
    assert.equal(index.byUuid.get('missing'), undefined);
    assert.equal(index.options, candidates);
    assert.deepEqual(calls[0].args, { tableUuid: 'table', columnUuid: 'column', expectedProjectSession: 'session' });
    done('1000 consumers share one request and first-match UUID index preserves backend order');
    let count = calls.length;
    await getReferenceOptions(scope, {}, 0);
    assert.equal(calls.length, ++count);
    await getReferenceOptions(scope, snapshot, 1);
    assert.equal(calls.length, ++count);
    await getReferenceOptions({ ...scope, expectedProjectSession: 'other-session' }, snapshot, 1);
    assert.equal(calls.length, ++count);
    await getReferenceOptions({ ...scope, tableUuid: 'other-table' }, snapshot, 1);
    assert.equal(calls.length, ++count);
    await getReferenceOptions(scope, snapshot, 1);
    assert.equal(calls.length, ++count);
    await getReferenceOptions({ ...scope, columnUuid: 'other-column' }, snapshot, 1);
    assert.equal(calls.length, ++count);
    await getReferenceOptions({ ...scope, targetTableUuid: 'other-target' }, snapshot, 1);
    assert.equal(calls.length, ++count);
    await getReferenceOptions({ ...scope, displayColumnUuid: 'other-display' }, snapshot, 1);
    assert.equal(calls.length, ++count);
    await getReferenceOptions(scope, snapshot, 1);
    assert.equal(calls.length, ++count);
    await getReferenceOptions(scope);
    await getReferenceOptions(scope);
    assert.equal(calls.length, count + 2);
    done('snapshot, refresh, session, table, column, target, display and config A→B→A isolation; no unscoped cache');
    const old = deferred(), current = deferred();
    const pending = [old, current];
    (globalThis as any).__invoke = () => pending.shift()!.promise;
    const rejectionSnapshot: any = {};
    const oldRequest = getReferenceOptions(scope, rejectionSnapshot, 0);
    const observedOld = oldRequest.catch(e => e);
    const newRequest = getReferenceOptions({ ...scope, targetTableUuid: 'new' }, rejectionSnapshot, 0);
    old.reject(new Error('old'));
    await observedOld;
    await Promise.resolve();
    assert.equal(getReferenceOptions({ ...scope, targetTableUuid: 'new' }, rejectionSnapshot, 0), newRequest);
    current.resolve(candidates);
    await newRequest;
    let retryCount = 0;
    (globalThis as any).__invoke = () => { retryCount++; return retryCount === 1 ? Promise.reject(new Error('retry')) : Promise.resolve(candidates); };
    const retrySnapshot: any = {};
    await getReferenceOptions(scope, retrySnapshot).catch(() => { });
    await getReferenceOptions(scope, retrySnapshot);
    assert.equal(retryCount, 2);
    done('rejected reads are retryable; obsolete rejection cannot evict a newer config request');
    const window = new Window({ url: 'http://reference.test' });
    for (const key of ['window', 'document', 'navigator', 'HTMLElement', 'Element', 'Node', 'Event', 'MouseEvent', 'CustomEvent'])
        Object.defineProperty(globalThis, key, { configurable: true, value: key === 'window' ? window : (window as any)[key] });
    (globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
    const container = document.createElement('div');
    document.body.appendChild(container);
    const root = createRoot(container);
    let mounted = true;
    try {
        const base: any = { row: { rowId: 'row', col: 'a' }, column: { key: 'col', idx: 0 }, rowIdx: 0, columnData: { uuid: 'column', data_name: 'Ref', reference_config: { target_table_uuid: 'target', display_column_uuid: 'display' } }, tableUuid: 'table', expectedProjectSession: 'session', tableData: {}, refreshVersion: 0 };
        const render = async (node: React.ReactNode) => { await act(async () => root.render(node)); };
        const flush = async (f: () => void) => { await act(async () => f()); };
        calls = [];
        (globalThis as any).__invoke = (command: any, args: any) => { calls.push({ command, args }); return Promise.resolve(candidates.slice(0, 2)); };
        await render(<>{Array.from({ length: 1000 }, (_, i) => <ReferenceCellRenderer key={i} {...base} row={{ rowId: String(i), col: i % 2 ? 'b' : 'a' }}/>)}</>);
        assert.equal(calls.length, 1);
        assert.equal(container.querySelectorAll('span').length, 1000);
        assert.equal(container.querySelectorAll('span')[0].textContent, 'Alpha');
        assert.equal(container.querySelectorAll('span')[1].textContent, '2:');
        await render(<ReferenceCellRenderer {...base} row={{ rowId: 'row', col: 'b' }}/>);
        assert.equal(calls.length, 1);
        (globalThis as any).__formatNumber = (n: number) => `localized-${n}`;
        await render(<ReferenceCellRenderer {...base} row={{ rowId: 'row', col: 'b' }}/>);
        assert.equal(container.textContent, 'localized-2:');
        delete (globalThis as any).__formatNumber;
        done('1000 rendered cells issue one IPC; value-only change reuses UUID index; fallback localizes on render');
        const oldResponse = deferred(), newResponse = deferred();
        let renderCalls = 0;
        (globalThis as any).__invoke = () => (++renderCalls === 1 ? oldResponse : newResponse).promise;
        const navigations: unknown[] = [];
        const fresh = { ...base, tableData: {}, onReferenceClick: (...args: unknown[]) => navigations.push(args) };
        await render(<ReferenceCellRenderer {...fresh}/>);
        assert.equal(container.textContent, 'Alpha', 'same-scope read keeps settled label');
        await render(<ReferenceCellRenderer {...fresh} refreshVersion={1}/>);
        await flush(() => newResponse.resolve([{ uuid: 'a', display_value: 'New target value' }]));
        assert.equal(container.textContent, 'New target value');
        await flush(() => oldResponse.resolve([{ uuid: 'a', display_value: 'Old target value' }]));
        assert.equal(container.textContent, 'New target value');
        assert.equal(renderCalls, 2);
        done('late pre-refresh result never replaces the current generation display');
        const settledLabel = container.querySelector('span')!;
        assert(settledLabel.classList.contains('cursor-pointer'));
        assert.equal(settledLabel.title, 'reference.openTarget');
        await flush(() => settledLabel.click());
        assert.deepEqual(navigations, [['target', 'a']]);
        const verifiedEcho = deferred();
        (globalThis as any).__invoke = () => verifiedEcho.promise;
        await render(<ReferenceCellRenderer {...fresh} refreshVersion={2}/>);
        assert.equal(container.textContent, 'New target value', 'same-scope save echo never replaces a settled label with Loading');
        const pendingLabel = container.querySelector('span')!;
        assert(!pendingLabel.classList.contains('cursor-pointer'));
        assert(!pendingLabel.classList.contains('hover:underline'));
        assert.equal(pendingLabel.title, '');
        await flush(() => pendingLabel.click());
        assert.equal(navigations.length, 1, 'retained unverified label cannot navigate');
        await flush(() => verifiedEcho.resolve([{ uuid: 'a', display_value: 'External target value' }]));
        assert.equal(container.textContent, 'External target value', 'external target edits still become visible');

        const refreshedLabel = container.querySelector('span')!;
        assert(refreshedLabel.classList.contains('cursor-pointer'));
        assert.equal(refreshedLabel.title, 'reference.openTarget');
        await flush(() => refreshedLabel.click());
        assert.equal(navigations.length, 2);
        done('retained labels advertise navigation only when verified and actionable');

        const transitions = [{ expectedProjectSession: 'changed-session' }, { tableUuid: 'changed-table' }, { columnData: { ...base.columnData, uuid: 'changed-column' } }, { columnData: { ...base.columnData, reference_config: { target_table_uuid: 'changed-target', display_column_uuid: 'display' } } }, { columnData: { ...base.columnData, reference_config: { target_table_uuid: 'target', display_column_uuid: 'changed-display' } } }, { tableData: {} }];
        for (const transition of transitions) {
            let response = deferred();
            (globalThis as any).__invoke = () => response.promise;
            await render(<ReferenceCellRenderer {...base} {...transition}/>);
            assert.equal(container.textContent, 'common.loading');
            await flush(() => response.resolve([{ uuid: 'a', display_value: 'Isolated' }]));
            assert.equal(container.textContent, 'Isolated');
        }
        done('renderer hides prior candidates immediately for session/table/column/config/snapshot changes');
        calls = [];
        (globalThis as any).__invoke = () => { calls.push(1); return Promise.resolve(candidates); };
        await render(<ReferenceCellRenderer {...base} row={{ rowId: 'empty', col: '' }} columnData={{ ...base.columnData, default_value: 'Default' }}/>);
        assert.equal(calls.length, 0);
        assert.equal(container.textContent, 'Default');
        await render(<ReferenceCellRenderer {...base} row={{ rowId: 'empty', col: '' }}/>);
        assert.equal(container.textContent, '');
        await render(<ReferenceCellRenderer {...base} tableData={{}} row={{ rowId: 'missing', col: 'missing' }}/>);
        assert.equal(container.textContent, 'reference.missing');
        await render(<ReferenceCellRenderer {...base} columnData={{ ...base.columnData, reference_config: null }}/>);
        assert.equal(container.textContent, 'reference.missing');
        const errorLog = console.error;
        console.error = () => { };
        (globalThis as any).__invoke = () => Promise.reject(new Error('expected'));
        await render(<ReferenceCellRenderer {...base} tableData={{}}/>);
        assert.equal(container.textContent, 'reference.loadFailed');
        console.error = errorLog;
        done('empty/default, missing target, unconfigured and failure states remain safe');
        let editorCalls = 0;
        (globalThis as any).__invoke = () => { editorCalls++; return Promise.resolve([{ uuid: 'a', display_value: `Fresh ${editorCalls}` }]); };
        const editorProps = { ...base, onRowChange: () => { } };
        await render(<ReferenceCellEditor {...editorProps}/>);
        assert.equal(editorCalls, 1);
        assert.equal(container.textContent, 'Fresh 1');
        await render(null);
        await render(<ReferenceCellEditor {...editorProps}/>);
        assert.equal(editorCalls, 2);
        assert.equal(container.textContent, 'Fresh 2');
        await render(<ReferenceCellEditor {...editorProps} refreshVersion={1}/>);
        assert.equal(editorCalls, 3);
        assert.equal(container.textContent, 'Fresh 3');
        const olderEditor = deferred(), newerEditor = deferred();
        let refreshCalls = 0;
        (globalThis as any).__invoke = () => (++refreshCalls === 1 ? olderEditor : newerEditor).promise;
        await flush(() => (globalThis as any).__popover.onRefresh());
        assert.equal((globalThis as any).__popover.refreshing, true);
        assert.equal(container.textContent, '');
        await flush(() => (globalThis as any).__popover.onRefresh());
        await flush(() => newerEditor.resolve([{ uuid: 'a', display_value: 'Newest refresh' }]));
        assert.equal(container.textContent, 'Newest refresh');
        assert.equal((globalThis as any).__popover.refreshing, false);
        await flush(() => olderEditor.resolve([{ uuid: 'a', display_value: 'Stale refresh' }]));
        assert.equal(container.textContent, 'Newest refresh');
        const unmounted = deferred();
        (globalThis as any).__invoke = () => unmounted.promise;
        await flush(() => (globalThis as any).__popover.onRefresh());
        await act(async () => root.unmount());
        mounted = false;
        await flush(() => unmounted.resolve([{ uuid: 'a', display_value: 'Unmounted' }]));
        assert.equal(container.textContent, '');
        done('editor reopen/event refresh reads fresh data; repeated refresh races and unmount are ignored');
        console.log(JSON.stringify({ passed: sections.length, sections }, null, 2));
    }
    finally {
        console.error = originalError;
        if (mounted)
            await act(async () => root.unmount());
        await window.happyDOM.close();
        delete (globalThis as any).__invoke;
        delete (globalThis as any).__popover;
        delete (globalThis as any).__formatNumber;
    }
}
