//! TypeScript accessors (ES2020) for the engine-independent JavaScript runtime.
//!
//! Delegate canonical-value validation, 64-bit integer decoding, reference indexing, and immutable snapshots to the runtime.
//! Do not introduce another JSON reader or engine-specific APIs into generated code.

use super::{CgColumn, CgModel, CgTable};
use crate::{types::ValueType, Result};

pub const DEFAULT_NAMESPACE: &str = "Devcel.Generated";

/// Validate TypeScript-specific reserved words and generated APIs in addition to shared portable-identifier checks.
pub(super) fn validate_names(model: &CgModel, namespace: &str, class_name: &str) -> Result<()> {
    const RESERVED: &str = "any arguments asserts async await bigint boolean break case catch class const constructor continue debugger declare default delete do else enum eval export extends false finally for function global if implements import in infer instanceof interface intrinsic is keyof let module never new null number object of out override package private protected public require return satisfies static string super switch symbol this throw true try type typeof undefined unique unknown using var void while with yield";
    let reserved = |name: &str| RESERVED.split_whitespace().any(|word| word == name);
    if reserved(class_name)
        || namespace.replace("::", ".").split('.').any(|name| {
            reserved(name)
                || [
                    "prototype",
                    "hasOwnProperty",
                    "isPrototypeOf",
                    "propertyIsEnumerable",
                    "toLocaleString",
                    "toString",
                    "valueOf",
                ]
                .contains(&name)
        })
    {
        return Err(crate::app_error::diagnostic(
            "error.codegen.typescriptIdentifier",
            serde_json::json!({}),
        ));
    }
    for table in &model.tables {
        if ["Runtime", "FromRuntime", "LoadJson"].contains(&table.type_base.as_str()) {
            return Err(crate::app_error::diagnostic(
                "error.codegen.nameConflict",
                serde_json::json!({"name": table.data_name, "scope": "TypeScript"}),
            ));
        }
        if table.columns.iter().any(|column| column.accessor == "Id") {
            return Err(crate::app_error::diagnostic(
                "error.codegen.nameConflict",
                serde_json::json!({"name": "Id", "scope": table.data_name}),
            ));
        }
    }
    for interface in &model.interfaces {
        if interface
            .members
            .iter()
            .any(|member| member.accessor == "Id")
        {
            return Err(crate::app_error::diagnostic(
                "error.codegen.nameConflict",
                serde_json::json!({"name": "Id", "scope": interface.type_name}),
            ));
        }
    }
    Ok(())
}

pub fn generate_with_class_name(model: &CgModel, namespace: &str, class_name: &str) -> String {
    let mut s = String::new();
    s.push_str("// <auto-generated> Devcel TypeScript SDK. Do not edit. </auto-generated>\n");
    s.push_str(&format!(
        "// project: {}\n",
        model
            .project_name
            .replace(['\r', '\n', '\u{2028}', '\u{2029}'], " ")
    ));
    s.push_str("// Requires ES2020 (bigint). Keep devcel-runtime.js and devcel-runtime.d.ts beside this file.\n");
    s.push_str("import * as __devcelRuntime from \"./devcel-runtime.js\";\n\n");
    s.push_str(&format!("export namespace {namespace} {{\n"));
    emit_select_enums(&mut s, model);
    emit_table_reference(&mut s, model);
    for interface in &model.interfaces {
        s.push_str(&format!("  export interface I{} {{\n", interface.type_name));
        for member in &interface.members {
            s.push_str(&format!(
                "    readonly {}: {};\n",
                member.accessor,
                property_type(&member.value_type, member.reference_target.as_deref())
            ));
            if member.value_type == ValueType::TableRef {
                s.push_str(&format!(
                    "    readonly {}Table: DevcelTableReference | undefined;\n",
                    member.accessor
                ));
            }
            if member.value_type == ValueType::Curve {
                s.push_str(&format!(
                    "    Sample{}(x: number): number;\n",
                    member.accessor
                ));
            }
        }
        s.push_str("  }\n\n");
    }
    for table in &model.tables {
        emit_table(&mut s, table, model);
    }
    emit_database(&mut s, model, class_name);
    s.push_str("}\n");
    s
}

fn emit_database(s: &mut String, model: &CgModel, class_name: &str) {
    s.push_str(&format!("  export class {class_name} {{\n"));
    s.push_str(
        "    private constructor(readonly Runtime: __devcelRuntime.DevcelRuntimeDatabase) {}\n",
    );
    s.push_str(&format!("    static FromJson(json: string): {class_name} {{\n      return new {class_name}(__devcelRuntime.DevcelRuntimeDatabase.fromJson(json));\n    }}\n"));
    s.push_str(&format!("    static FromRuntime(runtime: __devcelRuntime.DevcelRuntimeDatabase): {class_name} {{\n      return new {class_name}(runtime);\n    }}\n"));
    s.push_str("    /** Atomic reload; existing rows and tables retain their original snapshot. */\n    LoadJson(json: string): void { this.Runtime.loadJson(json); }\n");
    for table in &model.tables {
        let base = &table.type_base;
        s.push_str(&format!(
            "    get {base}(): {base}Table {{ return new {base}Table(this.Runtime.table({})); }}\n",
            literal(&table.data_name)
        ));
    }
    s.push_str("  }\n\n");
}

fn emit_table(s: &mut String, table: &CgTable, model: &CgModel) {
    let base = &table.type_base;
    s.push_str(&format!("  export class {base}Table {{\n"));
    s.push_str("    constructor(private readonly _table: __devcelRuntime.DevcelRuntimeTable | undefined) {}\n");
    s.push_str("    get Count(): number { return this._table?.rowCount ?? 0; }\n");
    s.push_str(&format!("    At(index: number): {base}Row | undefined {{\n      const row = this._table?.at(index);\n      return row === undefined ? undefined : new {base}Row(row);\n    }}\n"));
    s.push_str(&format!("    ById(uuid: string): {base}Row | undefined {{\n      const row = this._table?.rowById(uuid);\n      return row === undefined ? undefined : new {base}Row(row);\n    }}\n"));
    s.push_str(&format!("    get All(): readonly {base}Row[] {{\n      return this._table?.rows().map(row => new {base}Row(row)) ?? [];\n    }}\n  }}\n\n"));
    let interfaces = if table.implements.is_empty() {
        String::new()
    } else {
        format!(
            " implements {}",
            table
                .implements
                .iter()
                .map(|name| format!("I{name}"))
                .collect::<Vec<_>>()
                .join(", ")
        )
    };
    s.push_str(&format!("  export class {base}Row{interfaces} {{\n"));
    s.push_str("    constructor(private readonly _row: __devcelRuntime.DevcelRuntimeRow) {}\n");
    s.push_str("    get Id(): string { return this._row.id; }\n    get RowIndex(): number { return this._row.index; }\n");
    for column in &table.columns {
        emit_column(s, column, model);
        if let Some(options) = &column.select_options {
            let enum_name = super::select_enum_name(table, column);
            s.push_str(&format!(
                "    get {}Value(): {enum_name} | undefined {{\n      switch (this.{}) {{\n",
                column.accessor, column.accessor
            ));
            for (option, member) in options
                .iter()
                .zip(super::select_enum_members(&enum_name, options))
            {
                s.push_str(&format!(
                    "        case {}: return {enum_name}.{member};\n",
                    literal(option)
                ));
            }
            s.push_str("        default: return undefined;\n      }\n    }\n");
        }
    }
    s.push_str("  }\n\n");
}

fn emit_column(s: &mut String, column: &CgColumn, model: &CgModel) {
    let key = literal(&column.key);
    let name = &column.accessor;
    let ty = property_type(&column.value_type, column.reference_target.as_deref());
    if column.value_type == ValueType::Reference {
        if let Some(target) = &column.reference_target {
            let table = model
                .tables
                .iter()
                .find(|table| &table.type_base == target)
                .expect("reference targets are resolved from the same schema");
            s.push_str(&format!("    get {name}(): {ty} {{\n      const row = this._row.reference({key}, {});\n      return row === undefined ? undefined : new {target}Row(row);\n    }}\n", literal(&table.data_name)));
            return;
        }
    }
    let getter = match column.value_type {
        ValueType::I64 => "getI64",
        ValueType::U64 => "getU64",
        ValueType::U8
        | ValueType::I8
        | ValueType::U16
        | ValueType::I16
        | ValueType::U32
        | ValueType::I32
        | ValueType::F32
        | ValueType::F64 => "getNumber",
        ValueType::Boolean => "getBoolean",
        ValueType::Color32 => "getColor32",
        ValueType::ColorFloat => "getColorFloat",
        _ => "getString",
    };
    s.push_str(&format!(
        "    get {name}(): {ty} {{ return this._row.{getter}({key}); }}\n"
    ));
    if column.value_type == ValueType::TableRef {
        s.push_str(&format!("    get {name}Table(): DevcelTableReference | undefined {{\n      const table = this._row.tableReference({key}, {});\n      return table === undefined ? undefined : new DevcelTableReference(table);\n    }}\n", literal(column.table_ref_interface.as_deref().unwrap_or(""))));
    }
    if column.value_type == ValueType::Curve {
        s.push_str(&format!("    Sample{name}(x: number): number {{ return this._row.getCurve({key}).sample(x); }}\n"));
    }
}

fn emit_table_reference(s: &mut String, model: &CgModel) {
    s.push_str("  export class DevcelTableReference {\n");
    s.push_str("    constructor(private readonly _table: __devcelRuntime.DevcelRuntimeTable) {}\n");
    s.push_str("    get Name(): string { return this._table.name; }\n    get Id(): string { return this._table.uuid; }\n    get Count(): number { return this._table.rowCount; }\n");
    for table in &model.tables {
        let base = &table.type_base;
        s.push_str(&format!("    As{base}(): {base}Table | undefined {{\n      return this._table.name === {} ? new {base}Table(this._table) : undefined;\n    }}\n", literal(&table.data_name)));
    }
    s.push_str("  }\n\n");
}

fn emit_select_enums(s: &mut String, model: &CgModel) {
    for table in &model.tables {
        for column in &table.columns {
            if let Some(options) = &column.select_options {
                let name = super::select_enum_name(table, column);
                s.push_str(&format!("  export enum {name} {{\n"));
                for (option, member) in options
                    .iter()
                    .zip(super::select_enum_members(&name, options))
                {
                    s.push_str(&format!("    {member} = {},\n", literal(option)));
                }
                s.push_str("  }\n\n");
            }
        }
    }
}

fn property_type(value_type: &ValueType, reference_target: Option<&str>) -> String {
    match value_type {
        ValueType::I64 | ValueType::U64 => "bigint".into(),
        ValueType::U8
        | ValueType::I8
        | ValueType::U16
        | ValueType::I16
        | ValueType::U32
        | ValueType::I32
        | ValueType::F32
        | ValueType::F64 => "number".into(),
        ValueType::Boolean => "boolean".into(),
        ValueType::Color32 => "__devcelRuntime.Color32".into(),
        ValueType::ColorFloat => "__devcelRuntime.ColorFloat".into(),
        ValueType::Reference => reference_target
            .map(|name| format!("{name}Row | undefined"))
            .unwrap_or_else(|| "string".into()),
        _ => "string".into(),
    }
}

fn literal(value: &str) -> String {
    serde_json::to_string(value).expect("a string can always be encoded as JSON")
}
