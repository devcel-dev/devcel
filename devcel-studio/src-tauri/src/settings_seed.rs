pub fn source_files() -> &'static [(&'static str, &'static str)] {
    SOURCE_FILES
}
pub fn message_contract() -> Result<std::sync::Arc<TableData>> {
    static CONTRACT: once_cell::sync::OnceCell<std::sync::Arc<TableData>> =
        once_cell::sync::OnceCell::new();
    CONTRACT
        .get_or_try_init(|| {
            TableData::from_toml(include_str!(
                "../../app-settings/Tables/Localization/Messages.table.toml"
            ))
            .map(std::sync::Arc::new)
        })
        .cloned()
}

pub fn seed_project(dir: &Path) -> Result<PathBuf> {
    let files = source_files().to_vec();
    devcel_core::app_catalog::seed_project(dir, "studio.devcelproj.toml", &files)
}
pub fn compile_runtime(project: &Project) -> Result<devcel_core::app_catalog::CompiledAppSettings> {
    let contract = message_contract()?;
    devcel_core::app_catalog::compile_runtime(project, contract.as_ref())
}
