#!/usr/bin/env python3
"""Generate an experimental MasterMemory schema and JSON-to-binary builder."""
import argparse
import hashlib
import json
import os
import re
import tempfile
from pathlib import Path

TYPES = {
    "None": "string", "String": "string", "Select": "string", "DateTime": "string",
    "Curve": "DevcelCurve", "Reference": "DevcelRecordReference", "TableRef": "DevcelTableReference",
    "Color32": "DevcelColor32", "ColorFloat": "DevcelColorFloat", "Boolean": "bool",
    "U8": "byte", "I8": "sbyte", "U16": "ushort", "I16": "short",
    "U32": "uint", "I32": "int", "U64": "ulong", "I64": "long",
    "F32": "float", "F64": "double",
}

def literal(value):
    return json.dumps(value, ensure_ascii=True)

def identifier(value):
    if not isinstance(value, str) or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", value):
        raise ValueError(f"unsupported generated identifier: {value!r}")
    return value

def generate(bundle):
    if not isinstance(bundle, dict) or not isinstance(bundle.get("manifest"), dict):
        raise ValueError("missing manifest")
    manifest = bundle["manifest"]
    if type(manifest.get("schema_version")) is not int or manifest["schema_version"] != 1 or manifest.get("mode") != "full":
        raise ValueError("expected full bundle schema 1")
    tables = bundle.get("tables")
    if not isinstance(tables, list) or not tables:
        raise ValueError("expected at least one table")
    license_text = Path(__file__).with_name("LICENSE").read_text(encoding="utf-8").strip()
    output = [
        "/*\n" + license_text + "\n*/",
        "// Generated by Devcel. Rebuild if the schema changes.",
        "using System;",
        "using System.Collections.Generic;",
        "using System.Globalization;",
        "using MasterMemory;",
        "using MessagePack;",
        "using Newtonsoft.Json.Linq;",
        '[assembly: MasterMemoryGeneratorOptions(Namespace = "DevcelMasterMemory", PrefixClassName = "Devcel")]',
        "namespace DevcelMasterMemory {",
        "public static partial class BuildData {",
        "static string Read(JObject o, string n, string fallback) { var v = o[n]; if (v == null) return fallback; if (v.Type != JTokenType.String) throw new FormatException(\"Expected string: \" + n); return (string)v; }",
        "public static byte[] FromJson(string text) {",
        "var root=JObject.Parse(text);",
        'if ((int?)root["manifest"]?["schema_version"] != 1 || (string)root["manifest"]?["mode"] != "full") throw new FormatException("Expected full bundle schema 1");',
        'var tables=root["tables"] as JArray ?? throw new FormatException("Missing tables");',
        "var byName=new Dictionary<string,JObject>(StringComparer.Ordinal);",
        'foreach (var x in tables) { var t=x as JObject ?? throw new FormatException("Bad table"); byName.Add((string)t["name"],t); }',
        f'if (byName.Count != {len(tables)}) throw new FormatException("Table schema changed; regenerate");',
        "var builder=new DevcelDatabaseBuilder();",
    ]
    declarations = []
    handles = []
    table_by_uuid = {}
    for table in tables:
        uid = table.get("uuid")
        if not isinstance(uid, str) or not uid or uid in table_by_uuid:
            raise ValueError("missing or duplicate table UUID")
        table_by_uuid[uid] = identifier(table.get("name"))
    ref_targets = set()
    table_refs = []
    names = set()
    for table in tables:
        name = identifier(table.get("name"))
        if name in names: raise ValueError("duplicate table name: " + name)
        names.add(name)
        cls = "DevcelRow_" + name
        table_uuid = table.get("uuid")
        if not isinstance(table_uuid, str) or not table_uuid: raise ValueError("missing table UUID")
        cols = table.get("columns")
        if not isinstance(cols, list): raise ValueError("missing columns in " + name)
        interfaces = table.get("interfaces", [])
        if not isinstance(interfaces, list) or any(not isinstance(i, str) or not i for i in interfaces):
            raise ValueError("invalid table interfaces")
        expected_interfaces = literal(json.dumps(interfaces, separators=(",", ":")))
        decl = [f"[MemoryTable({literal(name)}), MessagePackObject(true)] public sealed class {cls} {{",
                '[PrimaryKey] public string RecordId { get; set; } = string.Empty;']
        block_start = len(output)
        handle_properties = []
        schema_checks = []
        output += [
            "{",
            f"var table=byName[{literal(name)}];",
            f'if ((string)table["uuid"] != {literal(table_uuid)}) throw new FormatException("Table UUID changed; regenerate");',
            f'if (!JToken.DeepEquals(table["interfaces"] ?? new JArray(), JToken.Parse({expected_interfaces}))) throw new FormatException("Table interfaces changed; regenerate");',
            'var columns=table["columns"] as JArray ?? throw new FormatException("Missing columns");',
            f'if (columns.Count != {len(cols)}) throw new FormatException("Column schema changed; regenerate");',
            "var schema=new Dictionary<string,string>(StringComparer.Ordinal);",
            "var defaults=new Dictionary<string,string>(StringComparer.Ordinal);",
            "var configs=new Dictionary<string,JObject>(StringComparer.Ordinal);",
            'foreach (var c in columns) { var n=(string)c["name"]; schema.Add(n,(string)c["data_type"]); defaults.Add(n,(string)c["default_value"] ?? string.Empty); configs.Add(n,(JObject)c); }',
            'var records=table["records"] as JArray ?? throw new FormatException("Missing records");',
            f"var rows=new List<{cls}>(records.Count);",
            "var ids=new HashSet<string>(StringComparer.Ordinal);",
            "foreach (var value in records) {",
            'var record=value as JObject ?? throw new FormatException("Bad record");',
            'var values=record["values"] as JObject ?? throw new FormatException("Missing values");',
            'foreach (var field in values.Properties()) if (!schema.ContainsKey(field.Name) || field.Value.Type != JTokenType.String) throw new FormatException("Unknown or non-string cell");',
            f"var row=new {cls}();",
            'row.RecordId=(string)record["id"] ?? throw new FormatException("Missing record id");',
            'if (!Guid.TryParse(row.RecordId, out _) || !ids.Add(row.RecordId)) throw new FormatException("Invalid or duplicate record id");',
        ]
        seen = set()
        for col in cols:
            colname = identifier(col.get("name"))
            if colname in seen: raise ValueError("duplicate column: " + colname)
            seen.add(colname)
            kind = col.get("data_type")
            if kind not in TYPES: raise ValueError("unsupported type: " + str(kind))
            ty = TYPES[kind]
            config = col.get("reference_config")
            target = config.get("target_table_uuid") if isinstance(config, dict) else None
            if kind == "Reference" and target:
                if target not in table_by_uuid:
                    raise ValueError("reference target is not in exported tables: " + str(target))
                target_name = table_by_uuid[target]
                ref_targets.add(target_name)
                ty = "DevcelRecordRef_" + target_name
            if kind == "TableRef":
                table_config = col.get("table_ref_config")
                interface = table_config.get("interface_uuid") if isinstance(table_config, dict) else None
                if table_config is not None and not interface:
                    raise ValueError("invalid TableRef interface")
                allowed = [(t["uuid"], identifier(t["name"])) for t in tables
                           if interface is None or interface in t.get("interfaces", [])]
                ty = "DevcelTableRef_" + hashlib.sha256((table_uuid + "\0" + colname).encode("utf-8")).hexdigest()
                table_refs.append((ty, allowed))
            prop = "Value_" + colname
            handle_properties.append(f"public {ty} {prop} => Current.{prop};")
            default = col.get("default_value")
            if default is None: default = ""
            if not isinstance(default, str): raise ValueError("bad default")
            decl += [f"public {ty} {prop} {{ get; set; }}" + (" = string.Empty;" if ty == "string" else "")]
            fallback = default
            if col.get("default_value") is None and kind == "Color32": fallback = "[255,255,255,255]"
            if col.get("default_value") is None and kind == "ColorFloat": fallback = "[1,1,1,1]"
            read = f"Read(values,{literal(colname)},{literal(fallback)})"
            if ty == "string": expr = read
            elif ty == "bool": expr = f"ParseBool({read})"
            elif kind in ("Color32", "ColorFloat"): expr = f"Parse{kind}({read})"
            elif kind == "Curve":
                curve_config = col.get("curve_config")
                if curve_config is None: start, end = "null", "null"
                else:
                    if not isinstance(curve_config, dict): raise ValueError("invalid curve config")
                    import math
                    def finite_number(v):
                        if type(v) not in (int,float) or not math.isfinite(v): raise ValueError("nonfinite curve config")
                        return repr(float(v)) + "d"
                    start = finite_number(curve_config.get("start_value"))
                    end = finite_number(curve_config.get("end_value"))
                expr = f"ParseCurve({read},{start},{end})"
            elif kind in ("Reference", "TableRef"):
                expr = f"new {ty} {{ Id = ParseReference({read}) }}"
            else: expr = f"Parse_{ty}({read})"
            for config_name in ("reference_config", "table_ref_config", "curve_config"):
                config_value = col.get(config_name)
                expected = "null" if config_value is None else "JToken.Parse(" + literal(json.dumps(config_value, separators=(",", ":"))) + ")"
                schema_checks.append(f'if (!JToken.DeepEquals(configs[{literal(colname)}][{literal(config_name)}], {expected})) throw new FormatException("Column configuration changed; regenerate");')
            schema_checks.append(f'if (!schema.TryGetValue({literal(colname)}, out var type_{colname}) || type_{colname} != {literal(kind)} || defaults[{literal(colname)}] != {literal(default)}) throw new FormatException("Column schema changed; regenerate");')
            output += [f"row.{prop}={expr};"]
            if kind == "TableRef":
                allow_expr = " && ".join(f"row.{prop}.Id != {literal(uid)}" for uid, _ in allowed) or "true"
                output += [f'if (!row.{prop}.IsEmpty && {allow_expr}) throw new FormatException("Table reference is missing or incompatible");']
        insert_at = next(i for i in range(block_start, len(output)) if output[i].startswith("var records="))
        output[insert_at:insert_at] = schema_checks
        output += [
            "rows.Add(row);",
            "}",
            "builder.Append(rows);",
            "}",
        ]
        decl += ["}"]
        declarations.extend(decl)
        handles += [
            f"public sealed class DevcelHandle_{name} {{",
            "readonly LiveDatabase source; readonly string id; ulong observed; bool resolved;",
            f"DevcelRow_{name} cached;",
            f"internal DevcelHandle_{name}(LiveDatabase source, string id) {{ this.source=source; this.id=id ?? throw new ArgumentNullException(nameof(id)); }}",
            f"public bool TryGet(out DevcelRow_{name} value) {{ var db=source.Current; if (!resolved || observed != source.Version) {{ db.DevcelRow_{name}Table.TryFindByRecordId(id,out cached); observed=source.Version; resolved=true; }} value=cached; return value != null; }}",
            f'public DevcelRow_{name} Current => TryGet(out var value) ? value : throw new KeyNotFoundException("Devcel record not found: " + id);',
        ] + handle_properties + ["}",
            f"public sealed partial class LiveDatabase {{ public DevcelHandle_{name} Get_{name}(string id) => new DevcelHandle_{name}(this,id); }}"]
    output += ["return builder.Build();", "}",
       'static bool ParseBool(string s) { s=s.Trim(); if (s.Length==0) return false; return bool.Parse(s); }']
    for ty in sorted(set(TYPES.values()) - {"string", "bool", "DevcelColor32", "DevcelColorFloat", "DevcelCurve", "DevcelRecordReference", "DevcelTableReference"}):
        if ty in ("float", "double"):
            output += [f'static {ty} Parse_{ty}(string s) {{ s=s.Trim(); var v = s.Length==0 ? ({ty})0 : {ty}.Parse(s, NumberStyles.Float, CultureInfo.InvariantCulture); if ({ty}.IsNaN(v) || {ty}.IsInfinity(v)) throw new FormatException("Non-finite value"); return v; }}']
        else:
            output += [f'static {ty} Parse_{ty}(string s) {{ s=s.Trim(); return s.Length==0 ? ({ty})0 : {ty}.Parse(s, CultureInfo.InvariantCulture); }}']
    output += ["}"] + declarations
    for target_name in sorted(ref_targets):
        output += [
            "[MessagePackObject] public struct DevcelRecordRef_" + target_name + " {",
            "[Key(0)] public string Id { get; set; }",
            "[IgnoreMember] public bool IsEmpty => string.IsNullOrEmpty(Id);",
            f"public DevcelRow_{target_name} Resolve(DevcelMemoryDatabase db) {{ if (IsEmpty) return null; return db.DevcelRow_{target_name}Table.TryFindByRecordId(Id, out var value) ? value : null; }}",
            "}",
        ]
    for ref_type, allowed in table_refs:
        output += [
            "[MessagePackObject] public struct " + ref_type + " {",
            "[Key(0)] public string Id { get; set; }",
            "[IgnoreMember] public bool IsEmpty => string.IsNullOrEmpty(Id);",
        ]
        for uid, target_name in sorted(allowed):
            output += [f"public global::DevcelMasterMemory.Tables.DevcelRow_{target_name}Table As_{target_name}(DevcelMemoryDatabase db) => Id == {literal(uid)} ? db.DevcelRow_{target_name}Table : null;"]
        output += ["}"]
    output += handles + [Path(__file__).with_name("support.cs.txt").read_text(encoding="utf-8"), Path(__file__).with_name("live.cs.txt").read_text(encoding="utf-8"), "}"]
    return "\n".join(output) + "\n"

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("bundle", type=Path)
    p.add_argument("output", type=Path)
    args = p.parse_args()
    text = generate(json.loads(args.bundle.read_text(encoding="utf-8")))
    # Unchanged schemas must not trigger Unity script recompilation.
    if args.output.is_file() and args.output.read_text(encoding="utf-8") == text:
        return
    # Construct everything before touching the destination; replace atomically.
    name = None
    try:
        with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", newline="\n",
                                         dir=args.output.parent, delete=False) as f:
            name = f.name
            f.write(text)
        os.replace(name, args.output)
        name = None
    finally:
        if name is not None:
            os.unlink(name)

if __name__ == "__main__": main()
