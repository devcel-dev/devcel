#!/usr/bin/env python3
"""Generate an experimental MasterMemory schema and JSON-to-binary builder."""
import argparse
import json
import os
import re
import tempfile
from pathlib import Path

TYPES = {
    "None": "string", "String": "string", "Select": "string", "DateTime": "string",
    "Curve": "string", "Reference": "string", "TableRef": "string",
    "Color32": "string", "ColorFloat": "string", "Boolean": "bool",
    "U8": "byte", "I8": "sbyte", "U16": "ushort", "I16": "short",
    "U32": "uint", "I32": "int", "U64": "ulong", "I64": "long",
    "F32": "float", "F64": "double",
}

def literal(value):
    return json.dumps(value, ensure_ascii=True)

def identifier(value):
    if not isinstance(value, str) or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", value):
        raise ValueError(f"unsupported generated identifier: {value!r}")
    return value

def generate(bundle):
    if not isinstance(bundle, dict) or not isinstance(bundle.get("manifest"), dict):
        raise ValueError("missing manifest")
    manifest = bundle["manifest"]
    if type(manifest.get("schema_version")) is not int or manifest["schema_version"] != 1 or manifest.get("mode") != "full":
        raise ValueError("expected full bundle schema 1")
    tables = bundle.get("tables")
    if not isinstance(tables, list) or not tables:
        raise ValueError("expected at least one table")
    output = [
        "// Generated by Devcel. Rebuild if the schema changes.",
        "using System;",
        "using System.Collections.Generic;",
        "using System.Globalization;",
        "using MasterMemory;",
        "using MessagePack;",
        "using Newtonsoft.Json.Linq;",
        '[assembly: MasterMemoryGeneratorOptions(Namespace = "DevcelMasterMemory", PrefixClassName = "Devcel")]',
        "namespace DevcelMasterMemory {",
        "public static class BuildData {",
        "static string Read(JObject o, string n, string fallback) { var v = o[n]; if (v == null) return fallback; if (v.Type != JTokenType.String) throw new FormatException(\"Expected string: \" + n); return (string)v; }",
        "public static byte[] FromJson(string text) {",
        "var root=JObject.Parse(text);",
        'if ((int?)root["manifest"]?["schema_version"] != 1 || (string)root["manifest"]?["mode"] != "full") throw new FormatException("Expected full bundle schema 1");',
        'var tables=root["tables"] as JArray ?? throw new FormatException("Missing tables");',
        "var byName=new Dictionary<string,JObject>(StringComparer.Ordinal);",
        'foreach (var x in tables) { var t=x as JObject ?? throw new FormatException("Bad table"); byName.Add((string)t["name"],t); }',
        f'if (byName.Count != {len(tables)}) throw new FormatException("Table schema changed; regenerate");',
        "var builder=new DevcelDatabaseBuilder();",
    ]
    declarations = []
    names = set()
    for table in tables:
        name = identifier(table.get("name"))
        if name in names: raise ValueError("duplicate table name: " + name)
        names.add(name)
        cls = "DevcelRow_" + name
        table_uuid = table.get("uuid")
        if not isinstance(table_uuid, str) or not table_uuid: raise ValueError("missing table UUID")
        cols = table.get("columns")
        if not isinstance(cols, list): raise ValueError("missing columns in " + name)
        decl = [f"[MemoryTable({literal(name)}), MessagePackObject(true)] public sealed class {cls} {{",
                '[PrimaryKey] public string RecordId { get; set; } = string.Empty;']
        block_start = len(output)
        schema_checks = []
        output += [
            "{",
            f"var table=byName[{literal(name)}];",
            f'if ((string)table["uuid"] != {literal(table_uuid)}) throw new FormatException("Table UUID changed; regenerate");',
            'var columns=table["columns"] as JArray ?? throw new FormatException("Missing columns");',
            f'if (columns.Count != {len(cols)}) throw new FormatException("Column schema changed; regenerate");',
            "var schema=new Dictionary<string,string>(StringComparer.Ordinal);",
            "var defaults=new Dictionary<string,string>(StringComparer.Ordinal);",
            'foreach (var c in columns) { var n=(string)c["name"]; schema.Add(n,(string)c["data_type"]); defaults.Add(n,(string)c["default_value"] ?? string.Empty); }',
            'var records=table["records"] as JArray ?? throw new FormatException("Missing records");',
            f"var rows=new List<{cls}>(records.Count);",
            "var ids=new HashSet<string>(StringComparer.Ordinal);",
            "foreach (var value in records) {",
            'var record=value as JObject ?? throw new FormatException("Bad record");',
            'var values=record["values"] as JObject ?? throw new FormatException("Missing values");',
            'foreach (var field in values.Properties()) if (!schema.ContainsKey(field.Name) || field.Value.Type != JTokenType.String) throw new FormatException("Unknown or non-string cell");',
            f"var row=new {cls}();",
            'row.RecordId=(string)record["id"] ?? throw new FormatException("Missing record id");',
            'if (!Guid.TryParse(row.RecordId, out _) || !ids.Add(row.RecordId)) throw new FormatException("Invalid or duplicate record id");',
        ]
        seen = set()
        for col in cols:
            colname = identifier(col.get("name"))
            if colname in seen: raise ValueError("duplicate column: " + colname)
            seen.add(colname)
            kind = col.get("data_type")
            if kind not in TYPES: raise ValueError("unsupported type: " + str(kind))
            ty = TYPES[kind]
            prop = "Value_" + colname
            default = col.get("default_value")
            if default is None: default = ""
            if not isinstance(default, str): raise ValueError("bad default")
            decl += [f"public {ty} {prop} {{ get; set; }}" + (" = string.Empty;" if ty == "string" else "")]
            read = f"Read(values,{literal(colname)},{literal(default)})"
            if ty == "string": expr = read
            elif ty == "bool": expr = f"ParseBool({read})"
            else: expr = f"Parse_{ty}({read})"
            schema_checks.append(f'if (!schema.TryGetValue({literal(colname)}, out var type_{colname}) || type_{colname} != {literal(kind)} || defaults[{literal(colname)}] != {literal(default)}) throw new FormatException("Column schema changed; regenerate");')
            output += [f"row.{prop}={expr};"]
        insert_at = next(i for i in range(block_start, len(output)) if output[i].startswith("var records="))
        output[insert_at:insert_at] = schema_checks
        output += [
            "rows.Add(row);",
            "}",
            "builder.Append(rows);",
            "}",
        ]
        decl += ["}"]
        declarations.extend(decl)
    output += ["return builder.Build();", "}",
       'static bool ParseBool(string s) { s=s.Trim(); if (s.Length==0) return false; return bool.Parse(s); }']
    for ty in sorted(set(TYPES.values()) - {"string", "bool"}):
        if ty in ("float", "double"):
            output += [f'static {ty} Parse_{ty}(string s) {{ s=s.Trim(); var v = s.Length==0 ? ({ty})0 : {ty}.Parse(s, NumberStyles.Float, CultureInfo.InvariantCulture); if ({ty}.IsNaN(v) || {ty}.IsInfinity(v)) throw new FormatException("Non-finite value"); return v; }}']
        else:
            output += [f'static {ty} Parse_{ty}(string s) {{ s=s.Trim(); return s.Length==0 ? ({ty})0 : {ty}.Parse(s, CultureInfo.InvariantCulture); }}']
    output += ["}"] + declarations + ["}"]
    return "\n".join(output) + "\n"

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("bundle", type=Path)
    p.add_argument("output", type=Path)
    args = p.parse_args()
    text = generate(json.loads(args.bundle.read_text(encoding="utf-8")))
    # Construct everything before touching the destination; replace atomically.
    name = None
    try:
        with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", newline="\n",
                                         dir=args.output.parent, delete=False) as f:
            name = f.name
            f.write(text)
        os.replace(name, args.output)
        name = None
    finally:
        if name is not None:
            os.unlink(name)

if __name__ == "__main__": main()
