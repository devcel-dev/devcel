    static void TestLiveOwner()
    {
        string full=File.ReadAllText("Assets/Generated/bundle.json");
        var asset=ScriptableObject.CreateInstance<Devcel.Unity.DevcelDatabaseAsset>();
        var source=new Devcel.Unity.DevcelProjectBundle {projectName="LiveQA",bundle=new TextAsset(full)};
        typeof(Devcel.Unity.DevcelDatabaseAsset).GetField("projects",BindingFlags.Instance|BindingFlags.NonPublic).SetValue(asset,new System.Collections.Generic.List<Devcel.Unity.DevcelProjectBundle>{source});
        var db=asset.GetDatabase("LiveQA",GameDatabase.Open,GameDatabase.FromJson);
        var handle=db.Get(EnemiesReferences.Slime);
        string previous=handle.Name;
        Directory.CreateDirectory(Application.streamingAssetsPath);
        string path=Path.Combine(Application.streamingAssetsPath,"live-owner.json");
        File.WriteAllText(path,full);
        source.bundle=null;source.streamingAssetsPath="live-owner.json";
        var reopened=asset.ReopenDatabase("LiveQA",GameDatabase.Open,GameDatabase.FromJson);
        Check(ReferenceEquals(db,reopened)&&ReferenceEquals(handle,reopened.Get(EnemiesReferences.Slime)),"TextAsset to file preserves database and handle owner");
        string changed=full.Replace("\"Enemy 1\"","\"LiveSlime\"");
        // Exported records use values.name; modify the fixture value and its hash together.
        changed=System.Text.RegularExpressions.Regex.Replace(changed,"(\"content_hash\"\\s*:\\s*\")[^\"]+", "$1live-owner-updated");
        File.WriteAllText(path,changed);
        Check(GameDatabase.ReloadOpenDatabases(path)==1,"Replacement owner registered for file reload");
        Check(handle.Name=="LiveSlime","Retained handle sees file reload");
        var serialized=new EnemiesReference(handle.Uuid);
        long before=GC.GetAllocatedBytesForCurrentThread();
        var current=db.Get(serialized);string name=current.Name;var nested=current.Friend;var iface=db.Get(EnemiesReferences.Slime.AsDamageable());
        foreach(var item in current.CatalogTable.AsProps()) { int hp=item.Hp; }
        double sampled=current.SampleGrowth(0.5); var date=current.WhenRfc3339; var color=current.Tint; ulong number=current.UlongValue;
        bool typed=sampled==20 && date.HasValue && color.R==128 && number==9007199254740993UL;
        long bytes=GC.GetAllocatedBytesForCurrentThread()-before;
        Check(typed,"Unity managed date/color/unsigned/curve access");
        Check(bytes==0,"Unity first acquisition after update allocates zero managed bytes: "+bytes);
        var doomed=GameDatabase.FromJson(full);
        var replacement=GameDatabase.FromJson(full);
        var retained=doomed.Get(EnemiesReferences.Slime);
        ((System.Collections.IDictionary)typeof(GameDatabase).GetField("LiveEnemies",BindingFlags.Instance|BindingFlags.NonPublic).GetValue(doomed))[retained.Uuid]=null;
        bool failed=false;
        try { doomed.TryReplaceDatabase(replacement); } catch(NullReferenceException) { failed=true; }
        Check(failed && doomed.Handle==IntPtr.Zero && replacement.Handle==IntPtr.Zero,"Failed owner publication closes both native owners");
        bool disposed=false;
        try { var ignored=retained.Name; } catch(ObjectDisposedException) { disposed=true; }
        Check(disposed,"Failed replacement never returns retained stale values");
        doomed.Dispose();replacement.Dispose();
        asset.CloseAll();UnityEngine.Object.DestroyImmediate(asset);
    }
    public static void Run()
    {
        try
        {
            TestLiveOwner();
            var a = ScriptableObject.CreateInstance<TypedReferenceAsset>();
            var b = ScriptableObject.CreateInstance<TypedReferenceAsset>();
            AssetDatabase.CreateAsset(a, "Assets/TypedReference.asset");
            AssetDatabase.CreateAsset(b, "Assets/TypedReferenceOther.asset");
            var settings = DevcelImporterSettings.Instance;
            settings.projects.Clear();
            var config = new DevcelProjectConfig { projectName="TypedQA", devcelProjectPath="Source", codeOutputFolder="Assets/Generated", jsonOutputFolder="Assets/Generated", bundleFileName="bundle.json", codeNamespace="Game.Master", codeClassName="GameDatabase", autoSync=false };
            settings.projects.Add(config); settings.Save();
            using(var serialized = new SerializedObject(a))
            {
                var field = serialized.FindProperty("enemy");
                Check(field.FindPropertyRelative("uuid") != null, "Inherited private UUID serializes");
                Undo.ClearAll();
                Capture(field)(EnemiesReferences.Slime.Uuid);
                Check(a.enemy.Uuid == EnemiesReferences.Slime.Uuid, "Picker callback scalar assignment");
                Undo.FlushUndoRecordObjects(); Undo.PerformUndo();
                Check(a.enemy.IsEmpty, "Picker Undo");
                Undo.PerformRedo(); Check(a.enemy.Uuid == EnemiesReferences.Slime.Uuid, "Picker Redo");
                serialized.Update();
                var target = serialized.FindProperty("target");
                Check(target.FindPropertyRelative("tableUuid") != null && target.FindPropertyRelative("uuid") != null, "Two inherited interface identities serialize");
                var reference = PropsReferences.Barrel.AsDamageable();
                Capture(target)(reference.TableUuid + "/" + reference.Uuid);
                Check(a.target.TableUuid == reference.TableUuid && a.target.Uuid == reference.Uuid, "Interface assignment retains both IDs");
                serialized.Update();
                var array = serialized.FindProperty("enemies");
                var safeLabel=typeof(DevcelTypedRecordReferenceDrawer).GetMethod("SafeFieldLabel",BindingFlags.Static|BindingFlags.NonPublic);
                var display=(GUIContent)safeLabel.Invoke(null,new object[]{array.GetArrayElementAtIndex(0),new GUIContent(EnemiesReferences.Slime.Uuid)});
                Check(display.text=="Element 0" && !display.text.Contains(EnemiesReferences.Slime.Uuid),"Array labels do not expose Unity's serialized UUID-derived caption");
                var stale = Capture(array.GetArrayElementAtIndex(0));
                array.GetArrayElementAtIndex(0).FindPropertyRelative("uuid").stringValue="first";
                array.GetArrayElementAtIndex(1).FindPropertyRelative("uuid").stringValue="second";
                serialized.ApplyModifiedProperties(); serialized.Update();
                stale = Capture(serialized.FindProperty("enemies").GetArrayElementAtIndex(0));
                serialized.FindProperty("enemies").MoveArrayElement(0,1); serialized.ApplyModifiedProperties();
                stale("wrong");
                Check(a.enemies[0].Uuid == "second" && a.enemies[1].Uuid == "first", "Reordered array rejects stale picker");
                serialized.Update(); Capture(serialized.FindProperty("enemy"))("missing-uuid");
                Check(a.enemy.Uuid == "missing-uuid", "Missing UUID preserved");
            }
            using(var multi = new SerializedObject(new UnityEngine.Object[]{a,b}))
            {
                var field = multi.FindProperty("enemy");
                Check(field.FindPropertyRelative("uuid").hasMultipleDifferentValues, "Mixed selection detected");
                Capture(field)(EnemiesReferences.Slime.Uuid);
                Check(a.enemy.Uuid == b.enemy.Uuid && a.enemy.Uuid == EnemiesReferences.Slime.Uuid, "Multi-object assignment");
            }
            var go = new GameObject("Typed references"); var sample = go.AddComponent<TypedReferenceSample>();
            using(var so = new SerializedObject(sample))
            {
                var item = so.FindProperty("targets").GetArrayElementAtIndex(0);
                var enemy = EnemiesReferences.Slime.AsDamageable();
                Capture(item)(enemy.TableUuid+"/"+enemy.Uuid);
                Check(sample.targets[0].TableUuid == enemy.TableUuid, "MonoBehaviour interface List assignment");
            }
            var prefab = PrefabUtility.SaveAsPrefabAsset(go,"Assets/TypedReference.prefab");
            var instance = (GameObject)PrefabUtility.InstantiatePrefab(prefab);
            using(var so = new SerializedObject(instance.GetComponent<TypedReferenceSample>())) Capture(so.FindProperty("enemy"))("missing-prefab");
            Check(PrefabUtility.HasPrefabInstanceAnyOverrides(instance,false), "Prefab override recorded");
            var picker = typeof(DevcelTypedRecordReferenceDrawer).Assembly.GetType("Devcel.Unity.Editor.DevcelReferencePicker");
            var choices = (Array)picker.GetMethod("LoadInterfaceChoices",BindingFlags.Static|BindingFlags.NonPublic).Invoke(null,new object[]{config, typeof(IDamageableReference).GetCustomAttribute<Devcel.Unity.DevcelInterfaceTargetAttribute>().InterfaceUuid, typeof(IDamageableReference).GetCustomAttributes<Devcel.Unity.DevcelImplementingTableAttribute>().ToArray()});
            Check(choices.Length==4,"Picker filters implementing tables and keeps duplicate row UUID identities");
            var choiceType = choices.GetType().GetElementType();
            var choiceId = choiceType.GetField("Id"); var choiceLabel = choiceType.GetField("Label"); var choiceRow = choiceType.GetField("RowNumber");
            Check(choices.Cast<object>().All(c => !((string)choiceLabel.GetValue(c)).Contains((string)choiceId.GetValue(c)) && !System.Text.RegularExpressions.Regex.IsMatch((string)choiceLabel.GetValue(c), @"[0-9a-f]{8}-[0-9a-f]{4}")), "Default picker labels hide identifiers");
            var unlabeled=choices.Cast<object>().Single(c => ((string)choiceLabel.GetValue(c))=="enemies / Row 2");
            Check((int)choiceRow.GetValue(unlabeled)==2,"Unlabeled fallback uses source-table row number");
            Check((bool)picker.GetMethod("Matches",BindingFlags.Static|BindingFlags.NonPublic).Invoke(null,new[]{unlabeled,choiceId.GetValue(unlabeled)}),"UUID paste remains searchable without displaying it");
            Check((int)choiceRow.GetValue(unlabeled)==2,"Filtering does not renumber rows");
            var preview=typeof(DevcelTypedRecordReferenceDrawer).Assembly.GetType("Devcel.Unity.Editor.DevcelRecordPreview");
            var read=preview.GetMethod("Read",BindingFlags.Static|BindingFlags.NonPublic);
            string original=File.ReadAllText("Assets/Generated/bundle.json");
            Func<Type,Array> inspect=referenceType => (Array)read.Invoke(null,new object[]{config,typeof(GameDatabase),referenceType,EnemiesReferences.Slime.Uuid,EnemiesReferences.Slime.AsDamageable().TableUuid});
            var damage=inspect(typeof(IDamageableReference));var armor=inspect(typeof(IArmoredReference));
            Func<Array,string> hp=items => (string)items.GetType().GetElementType().GetField("Value").GetValue(items.Cast<object>().Single(c => (string)c.GetType().GetField("Name").GetValue(c)=="Hp"));
            Check(hp(damage)=="42" && hp(armor)=="100","Preview uses correct distinct interface projection");
            Check(File.ReadAllText("Assets/Generated/bundle.json")==original,"Preview leaves imported data byte-for-byte unchanged");
            bool missingPreview=false;try {read.Invoke(null,new object[]{config,typeof(GameDatabase),typeof(EnemiesReference),"missing-preview",null});}catch(TargetInvocationException ex){missingPreview=ex.InnerException is InvalidDataException;}
            Check(missingPreview,"Missing preview fails without replacing saved identity");
            Check((string)preview.GetMethod("Format",BindingFlags.Static|BindingFlags.NonPublic).Invoke(null,new object[]{EnemiesReferences.Slime.Uuid})=="[identifier]","Preview hides identifier-bearing text by default");

            var loadTable=picker.GetMethod("LoadChoices",BindingFlags.Static|BindingFlags.NonPublic);
            string tableId=typeof(EnemiesReference).GetCustomAttribute<Devcel.Unity.DevcelRecordTargetAttribute>().TableUuid;
            Func<Array> tableChoices=()=> (Array)loadTable.Invoke(null,new object[]{config,"enemies",tableId});
            var beforeChoices=tableChoices();
            Check((string)choiceLabel.GetValue(beforeChoices.GetValue(0))=="Slime","Table picker uses authored label metadata");
            string unlabeledId=((string)choiceId.GetValue(unlabeled)).Split('/')[1];
            try {
                string swapped=original.Replace(EnemiesReferences.Slime.Uuid,"__swap_record_identity__").Replace(unlabeledId,EnemiesReferences.Slime.Uuid).Replace("__swap_record_identity__",unlabeledId);
                File.WriteAllText("Assets/Generated/bundle.json",swapped);
                var reordered=tableChoices().Cast<object>().Single(c=>(string)choiceId.GetValue(c)==unlabeledId);
                Check((int)choiceRow.GetValue(reordered)==1 && (string)choiceLabel.GetValue(reordered)=="Row 1","Reimport updates source row number while UUID identity is retained");
                string refreshed=original.Replace("\"Enemy 1\"","\"Preview refreshed\"");
                File.WriteAllText("Assets/Generated/bundle.json",refreshed);
                var fresh=(Array)read.Invoke(null,new object[]{config,typeof(GameDatabase),typeof(EnemiesReference),EnemiesReferences.Slime.Uuid,null});
                var name=fresh.Cast<object>().Single(c=>(string)c.GetType().GetField("Name").GetValue(c)=="Name");
                Check((string)name.GetType().GetField("Value").GetValue(name)=="Preview refreshed","Preview reads current imported values rather than a retained snapshot");
            } finally { File.WriteAllText("Assets/Generated/bundle.json",original); }
            Check(File.ReadAllText("Assets/Generated/bundle.json")==original,"Synthetic reimport fixture restored exactly");

            var wraps=preview.GetMethod("UsesMultiline",BindingFlags.Static|BindingFlags.NonPublic);
            Check(!(bool)wraps.Invoke(null,new object[]{"42",20f,140f}),"Short preview values stay in the right-aligned value column");
            Check((bool)wraps.Invoke(null,new object[]{"long",180f,140f}) && (bool)wraps.Invoke(null,new object[]{"a\nb",20f,140f}),"Narrow and multiline preview values wrap without losing content");
            var style=preview.GetMethod("ValueStyle",BindingFlags.Static|BindingFlags.NonPublic);
            Check(((GUIStyle)style.Invoke(null,new object[]{false,new GUIStyle()})).alignment==TextAnchor.UpperRight && ((GUIStyle)style.Invoke(null,new object[]{true,new GUIStyle()})).alignment==TextAnchor.UpperRight,"Preview value alignment remains right-aligned for short and wrapped text");
            Check(typeof(DevcelTypedRecordReferenceDrawer).Assembly.GetType("Devcel.Unity.Editor.DevcelReferencePicker").GetMethod("ShowDetailsMenu",BindingFlags.Static|BindingFlags.NonPublic)==null,"Reference UI exposes no identifier details dialog");
            var companion=preview.GetMethod("IsTableReferenceCompanion",BindingFlags.Static|BindingFlags.NonPublic);
            Check(!(bool)companion.Invoke(null,new object[]{typeof(IndependentColumns).GetProperty("Foo"),typeof(IndependentColumns),typeof(GameDatabase)}),"Independent Foo/FooTable columns are both visible");
            Check((bool)companion.Invoke(null,new object[]{typeof(EnemiesHandle).GetProperty("Catalog"),typeof(EnemiesHandle),typeof(GameDatabase)}),"Only actual generated TableRef companion strings are hidden");
            var rowPreview=(Array)read.Invoke(null,new object[]{config,typeof(GameDatabase),typeof(EnemiesReference),EnemiesReferences.Slime.Uuid,null});
            Func<string,string> previewValue=field=>(string)rowPreview.Cast<object>().Single(c=>(string)c.GetType().GetField("Name").GetValue(c)==field).GetType().GetField("Value").GetValue(rowPreview.Cast<object>().Single(c=>(string)c.GetType().GetField("Name").GetValue(c)==field));
            Check(previewValue("Friend")=="props / Barrel","Nested record summary uses actual table and authored label without recursion");
            Check(previewValue("Catalog Table")=="props (1 records)","Table reference summary identifies target and resolved count");
            using(var missingOwner=GameDatabase.FromJson(original)) {
                var missingTable=Activator.CreateInstance(typeof(DevcelTableHandle),BindingFlags.Instance|BindingFlags.NonPublic,null,new object[]{missingOwner,"missing-table",""},null);
                var describe=preview.GetMethod("DescribeReference",BindingFlags.Static|BindingFlags.NonPublic);
                var emptyTables=Array.CreateInstance(describe.GetParameters()[2].ParameterType.GetElementType(),0);
                Check((string)describe.Invoke(null,new object[]{missingTable,typeof(GameDatabase),emptyTables})=="Missing table","Missing table handles are not presented as valid references");
            }

            using(var db = GameDatabase.FromJson(File.ReadAllText("Assets/Generated/bundle.json")))
            {
                Check(db.Get(a.target).Hp == 91,"Unity native interface resolution");
                Check(db.Get(EnemiesReferences.Slime.AsArmored()).Hp == 100,"Distinct same-name interface projection");
            }
            AssetDatabase.SaveAssets();
            string yaml = File.ReadAllText("Assets/TypedReference.asset");
            Check(yaml.Contains(a.target.TableUuid) && yaml.Contains(a.target.Uuid),"Asset persists both stable IDs");
            UnityEngine.Object.DestroyImmediate(instance); UnityEngine.Object.DestroyImmediate(go);
            Selection.activeObject=a;
            Debug.Log("TYPED_REFERENCE_UNITY_TESTS_PASS " + count);
            File.WriteAllText("../unity-tests-result.txt","PASS " + count);
        }
        catch(Exception error) { Debug.LogException(error); File.WriteAllText("../unity-tests-result.txt",error.ToString()); throw; }
    }
